// Copies ArcwayBounties' creation bytecode from Foundry's build into lib/bountiesBytecode.ts,
// so the app's deploy page ships exactly what `forge test` tested.
//   node scripts/bounties-bytecode.mjs          write the file (run `forge build` in contracts/ first)
//   node scripts/bounties-bytecode.mjs --check  fail if the file doesn't match the current build
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = join(root, "contracts/out/ArcwayBounties.sol/ArcwayBounties.json");
const target = join(root, "lib/bountiesBytecode.ts");

const built = JSON.parse(readFileSync(artifact, "utf8")).bytecode.object;
if (!/^0x[0-9a-f]+$/.test(built)) throw new Error("No bytecode in the artifact. Run `forge build` in contracts/.");

/** Drops the trailing CBOR metadata (its length is the last two bytes), which can differ between machines. */
const code = (hex) => hex.slice(0, hex.length - (parseInt(hex.slice(-4), 16) + 2) * 2);
const sha = (hex) => createHash("sha256").update(code(hex)).digest("hex").slice(0, 16);

if (process.argv.includes("--check")) {
  const shipped = readFileSync(target, "utf8").match(/"(0x[0-9a-f]+)"/)?.[1];
  if (!shipped || code(shipped) !== code(built)) {
    console.error("lib/bountiesBytecode.ts is out of date. Run `node scripts/bounties-bytecode.mjs` after `forge build`.");
    process.exit(1);
  }
  console.log(`ArcwayBounties bytecode matches the build (${sha(built)}).`);
} else {
  writeFileSync(target, `// Generated by scripts/bounties-bytecode.mjs from contracts/src/ArcwayBounties.sol. Do not edit.
// CI checks this matches a fresh \`forge build\`. Code hash (without metadata): ${sha(built)}
export const bountiesBytecode = "${built}" as const;
`);
  console.log(`Wrote lib/bountiesBytecode.ts (${(built.length - 2) / 2} bytes, ${sha(built)}).`);
}
